//! Messages captured off this machine's live session bus with
//! `dbus-monitor --pcap`, which records the bytes a message was delivered as.
//!
//! **Every array in this file is a real capture, not a hand-computed one.** The
//! producers are named per vector and are three independent implementations:
//! Chromium's `MPRIS` service, the `gdbus` tool from `GLib`, and `dbus-broker` itself. They are
//! here because the container padding rules fail silently - the specification's
//! answer to a malformed message is to drop the connection without notice - so
//! the only trustworthy check on the marshaller is byte equality against
//! something that already works.
//!
//! To capture more: run `dbus-monitor --session --pcap > out.pcap` in one
//! shell, provoke the traffic in another, and read the records out. A pcap
//! record is a 16-byte header followed by the message exactly as it went over
//! the socket.

